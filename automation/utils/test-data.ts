export function uniqueText(prefix: string): string {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

export function buildPostPayload(): { title: string; body: string; userId: number } {
  return { title: uniqueText('playwright-post'), body: 'Generated by an automated API test.', userId: 1 };
}
