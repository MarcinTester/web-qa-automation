export interface RegistrationUser {
  firstName: string;
  lastName: string;
  email: string;
  password: string;
}

export function uniqueText(prefix: string): string {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

export function buildPostPayload(): { title: string; body: string; userId: number } {
  return {
    title: uniqueText('playwright-post'),
    body: 'Generated by an automated API test.',
    userId: 1
  };
}

export function buildRegistrationUser(overrides: Partial<RegistrationUser> = {}): RegistrationUser {
  const uniqueId = uniqueText('qa-user');
  return {
    firstName: 'Test',
    lastName: 'User',
    email: `${uniqueId}@qa-shop.local`,
    password: 'Password123!',
    ...overrides
  };
}
